// IPMA weather stations: URLs, area lookup and row shaping.
// Shared by the browser bundle, the Pages Functions and
// scripts/build-stations.mjs — keep it free of DOM/React.

import { STATION_AREAS } from '../data/stationAreas.js'
import { IPMA_AREAS } from '../data/ipmaAreas.js'
import { isValid, windDir } from './format.js'
import { formatLisbonInstant, slugify } from './share.js'

// /estacao/<id>-<name>. Only the leading id is authoritative: IPMA renames
// stations now and then, and old links must keep resolving (the page and the
// middleware canonicalise to the current name).
export function stationSlug(id, name) {
	const s = slugify(name ?? '')
	return s ? `${id}-${s}` : String(id)
}

export function stationPath(id, name) {
	return `/estacao/${stationSlug(id, name)}`
}

export function stationIdFromSlug(slug) {
	const m = String(slug ?? '').match(/^(\d+)/)
	return m ? Number(m[1]) : null
}

// IPMA area code for a station (generated by scripts/build-stations.mjs).
// Unknown (newer) stations fall back to the nearest area centroid.
export function stationArea(id, lat, lng) {
	const known = STATION_AREAS[id]
	if (known) return known
	if (lat == null || lng == null) return null
	let best = null
	let bestD = Infinity
	for (const [code, a] of Object.entries(IPMA_AREAS)) {
		const d = (a.lat - lat) ** 2 + (a.lng - lng) ** 2
		if (d < bestD) {
			bestD = d
			best = code
		}
	}
	return best
}

// Station catalog (GeoJSON features from /api/stations) + latest-hour
// observations → flat rows. Stations without a reading this hour keep
// obs = null so callers can decide whether to list them.
export function stationRows(catalog, obsByStation) {
	const rows = []
	for (const f of catalog ?? []) {
		const id = f?.properties?.idEstacao
		const coords = f?.geometry?.coordinates
		if (id == null || !coords) continue
		const [lng, lat] = coords
		rows.push({
			id,
			name: f.properties.localEstacao,
			lat,
			lng,
			area: stationArea(id, lat, lng),
			obs: obsByStation?.[String(id)] ?? null,
		})
	}
	return rows
}

// A reading or null — collapses IPMA's -99 sentinel.
export function reading(obs, field) {
	const v = obs?.[field]
	return isValid(v) ? v : null
}

export function haversineKm(a, b) {
	const toRad = (d) => (d * Math.PI) / 180
	const dLat = toRad(b.lat - a.lat)
	const dLng = toRad(b.lng - a.lng)
	const s = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLng / 2) ** 2
	return 2 * 6371 * Math.asin(Math.sqrt(s))
}

// FogosPT hour keys are UTC without a zone ('2026-11-09T14:00'); the station
// series endpoint uses full ISO with Z. Both → Date.
export function obsDate(key) {
	if (!key) return null
	const s = String(key)
	const d = new Date(/[zZ]|[+-]\d{2}:?\d{2}$/.test(s) ? s : `${s.length === 16 ? `${s}:00` : s}Z`)
	return Number.isNaN(d.getTime()) ? null : d
}

// Display helpers (pt-PT decimal comma). Return null for missing readings so
// callers can hide the row.
function num(v, digits) {
	return v.toLocaleString('pt-PT', { minimumFractionDigits: digits, maximumFractionDigits: digits })
}

export function fmtTemp(v) {
	return v == null ? null : `${num(v, 1)} °C`
}

export function fmtMm(v) {
	return v == null ? null : `${num(v, 1)} mm`
}

export function fmtPct(v) {
	return v == null ? null : `${Math.round(v)}%`
}

export function fmtKmh(v) {
	return v == null ? null : `${Math.round(v)} km/h`
}

export function fmtHpa(v) {
	return v == null ? null : `${Math.round(v)} hPa`
}

export { windDir }

// Title/description for a station page — same text on the server (meta
// tags) and in the browser. `row` comes from stationRows(); `hour` is the
// FogosPT hour key of the latest observations.
export function stationSeo(row, hour) {
	const areaName = row.area ? IPMA_AREAS[row.area]?.name : null
	const title = `${row.name} — estação meteorológica IPMA`
	const o = row.obs
	const parts = [
		fmtTemp(reading(o, 'temperatura')),
		reading(o, 'intensidadeVentoKM') != null
			? `vento ${fmtKmh(reading(o, 'intensidadeVentoKM'))}${windDir(reading(o, 'idDireccVento')) ? ` ${windDir(reading(o, 'idDireccVento'))}` : ''}`
			: null,
		reading(o, 'humidade') != null ? `humidade ${fmtPct(reading(o, 'humidade'))}` : null,
		reading(o, 'precAcumulada') != null
			? reading(o, 'precAcumulada') > 0
				? `chuva ${fmtMm(reading(o, 'precAcumulada'))} na última hora`
				: 'sem chuva'
			: null,
	].filter(Boolean)
	const when = obsDate(hour)
	const description = parts.length
		? `${when ? `Às ${formatLisbonInstant(when.getTime()).split(', ')[1]}` : 'Agora'}: ${parts.join(', ')}. Temperatura, vento, chuva e humidade hora a hora${areaName ? ` — ${areaName}` : ''}.`
		: `Observações hora a hora da estação meteorológica IPMA de ${row.name}${areaName ? ` (${areaName})` : ''}: temperatura, vento, chuva e humidade.`
	return { title, description, path: stationPath(row.id, row.name) }
}
