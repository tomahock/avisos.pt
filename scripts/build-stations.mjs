// Regenerates the station → IPMA area table and the station URLs in the
// sitemap. Run when IPMA adds/moves stations:
//
//   node scripts/build-stations.mjs
//
// Reads the public station catalog from FogosPT (no key needed for this
// endpoint) and assigns each station to the area whose polygon contains it
// (continental: district; islands: concelho → island zone via
// islandConcelhos.js). Stations just off the simplified coastline go to the
// polygon with the nearest vertex. Madeira's mountain zone (MRM) has no
// polygon, so mountain stations land in MCN/MCS — same limitation as the map.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { IPMA_AREAS, codeFromContinentalName } from '../src/data/ipmaAreas.js'
import { codeForFeature } from '../src/data/islandConcelhos.js'
import { stationPath } from '../src/utils/stations.js'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'))

const features = [
	...read('public/data/pt-continental.geojson').features,
	...read('public/data/pt-arquipelagos.geojson').features,
]
	.map((f) => ({ code: codeForFeature(f, codeFromContinentalName), geometry: f.geometry }))
	.filter((f) => f.code)

function polygonsOf(g) {
	return g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : []
}

// Ray casting on the outer ring minus holes.
function inRing([x, y], ring) {
	let inside = false
	for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
		const [xi, yi] = ring[i]
		const [xj, yj] = ring[j]
		if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside
	}
	return inside
}

function contains(geometry, pt) {
	return polygonsOf(geometry).some(([outer, ...holes]) => inRing(pt, outer) && !holes.some((h) => inRing(pt, h)))
}

function nearestCode(pt) {
	let best = null
	let bestD = Infinity
	for (const f of features) {
		for (const poly of polygonsOf(f.geometry)) {
			for (const [x, y] of poly[0]) {
				const d = (x - pt[0]) ** 2 + (y - pt[1]) ** 2
				if (d < bestD) {
					bestD = d
					best = f.code
				}
			}
		}
	}
	return best
}

const res = await fetch('https://api.fogos.pt/v2/weather/stations/ipma', {
	headers: { 'User-Agent': 'AvisosPT/1.0 (+https://avisos.pt) build-stations' },
})
if (!res.ok) throw new Error(`stations: HTTP ${res.status}`)
const stations = await res.json()

const areas = {}
let fallback = 0
for (const s of stations) {
	const pt = s.geometry?.coordinates
	const id = s.properties?.idEstacao
	if (!pt || id == null) continue
	let code = features.find((f) => contains(f.geometry, pt))?.code
	if (!code) {
		code = nearestCode(pt)
		fallback++
	}
	areas[id] = code
}

const sorted = Object.fromEntries(Object.entries(areas).sort(([a], [b]) => Number(a) - Number(b)))
fs.writeFileSync(
	path.join(root, 'src/data/stationAreas.js'),
	'// Generated by scripts/build-stations.mjs — do not edit by hand.\n' +
		'// IPMA station id → IPMA area code.\n' +
		'export const STATION_AREAS = {\n' +
		Object.entries(sorted).map(([id, code]) => `\t${id}: '${code}',`).join('\n') +
		'\n}\n'
)

// Sitemap: replace the generated station block.
const sitemapPath = path.join(root, 'public/sitemap.xml')
const START = '\t<!-- estacoes:start (scripts/build-stations.mjs) -->'
const END = '\t<!-- estacoes:end -->'
let sitemap = fs.readFileSync(sitemapPath, 'utf8')
const a = sitemap.indexOf(START)
const b = sitemap.indexOf(END)
if (a !== -1 && b !== -1) sitemap = sitemap.slice(0, a) + sitemap.slice(b + END.length + 1)
const urls = stations
	.filter((s) => s.properties?.idEstacao != null)
	.map((s) => `\t<url>\n\t\t<loc>https://avisos.pt${stationPath(s.properties.idEstacao, s.properties.localEstacao)}</loc>\n\t\t<changefreq>hourly</changefreq>\n\t\t<priority>0.5</priority>\n\t</url>\n`)
	.join('')
sitemap = sitemap.replace('</urlset>', `${START}\n${urls}${END}\n</urlset>`)
fs.writeFileSync(sitemapPath, sitemap)

const perArea = {}
for (const c of Object.values(areas)) perArea[c] = (perArea[c] ?? 0) + 1
console.log(`${Object.keys(areas).length} estações; ${fallback} por vértice mais próximo`)
console.log(Object.entries(perArea).map(([c, n]) => `${IPMA_AREAS[c]?.chip ?? IPMA_AREAS[c]?.name ?? c}: ${n}`).join(', '))
